export function unsplash(id: string, w = 1200, q = 75): string {
  return `https://images.unsplash.com/${id}?auto=format&fit=crop&w=${w}&q=${q}`;
}

export function flagUrl(code: string, size: "w20" | "w40" | "w80" | "w160" = "w80"): string {
  return `https://flagcdn.com/${size}/${code}.png`;
}

